from __future__ import annotations

from textwrap import dedent


def draft_prompt(topic: str, keywords: list[str], min_chars: int, max_chars: int) -> str:
    keyword_text = "、".join(keywords)
    return dedent(
        f"""
        以下のトピックについて、SEOを意識した日本語ブログ記事を書いてください。

        トピック: {topic}
        文字数: {min_chars}〜{max_chars}字
        構成:
        - 導入: 読者の悩みと記事で得られる成果を明確にする
        - 全体像: 初心者が仕組みを理解できるように説明する
        - ステップ・バイ・ステップ: 具体的な作業順序を番号付きで書く
        - 専門家目線のチェックポイント: 失敗しやすい箇所、判断基準、注意点を書く
        - 画像で説明すべき箇所: 記事内に入れると理解が深まる図解や写真の内容を提案する
        - よくある失敗と対策: 初心者が詰まりやすい原因と解決策を書く
        - 成果を測るKPI: 何を見れば改善できるかを書く
        - まとめ: 次に取るべき行動を整理する
        トーン: 専門的だが読みやすい。初心者にも分かるように、用語の直後に具体例を書く。
        SEOキーワード: {keyword_text}
        出力: Markdown形式（見出し・箇条書き・太字を活用）

        重要:
        - NotionのAIスロップ防止基準を満たしてください。Hiroまたはこのサイト固有の実行ログ・検証結果・一次情報・具体データを必ず含めてください。
        - 数字を書く場合は、実測・ログ・出典・前提条件のいずれかを添えてください。
        - 画像で説明すべき箇所、視覚的証拠、スクリーンショットや図解の案を必ず1つ入れてください。
        - 反論、限界、使えないケース、注意点を正直に書いてください。
        - 読者が読了後すぐに取れる具体的アクションを1つ以上提示してください。
        - 類似記事との差別化ポイントを明確にしてください。
        - 「重要なのは」「本質は」「まとめると」「〜だけでいい」「〜しなくていい」のようなAI定型・思考停止表現は避けてください。
        - 不確実な情報は断定しないでください。
        - 投資助言と誤解される表現は避け、一般的な情報提供として書いてください。
        - 最初の行に H1 見出しとして魅力的な記事タイトルを書いてください。
        - 一般論だけで終えず、読者が実際に手を動かせる手順、チェックリスト、判断基準を必ず入れてください。
        - 有料記事や有料マニュアルに誘導しても不自然ではない密度で、無料部分だけでも役立つ情報量にしてください。
        """
    ).strip()


def review_prompt(draft: str) -> str:
    return dedent(
        f"""
        以下のブログ記事をレビューし、改善版を出力してください。

        チェック項目:
        1. 事実誤認がないか
        2. 論理の飛躍がないか
        3. SEO的に改善できる点（見出し構成、キーワード配置）
        4. 読みやすさ（文の長さ、段落分け）
        5. 導入文のフック（読者の興味を引けるか）
        6. 初心者向けのステップ・バイ・ステップになっているか
        7. 専門家目線のチェックポイント、失敗対策、KPIが含まれているか
        8. 画像で説明すべき内容が、本文の理解を助ける具体的な提案になっているか
        9. Hiroまたはこのサイト固有の実行ログ・検証結果・一次情報があるか
        10. 反論・限界・読後アクション・差別化があるか

        改善した完成版の記事全文を Markdown で出力してください。薄い一般論は削り、具体的な手順・確認方法・改善方法を増やしてください。
        front matter は付けないでください。

        --- 元記事 ---
        {draft}
        """
    ).strip()


def final_check_prompt(improved: str) -> str:
    return dedent(
        f"""
        以下のブログ記事の最終チェックをしてください。
        問題があれば修正した完成版を、なければそのまま出力してください。

        チェック項目:
        1. 誤字脱字
        2. Markdown の構文エラー
        3. 不自然な日本語表現
        4. 記事タイトルが魅力的か（クリックしたくなるか）
        5. 読者がお金を払って深掘りしたくなるだけの専門性と実務密度があるか
        6. 初心者が次に何をすればよいか分かるか
        7. AIスロップ防止基準で8/10以上になるだけの一次情報、視覚証拠、限界、差別化があるか

        修正済みの記事全文を Markdown で出力してください。
        front matter は付けないでください。

        --- 記事 ---
        {improved}
        """
    ).strip()
